-- Supabase Anonymous Bulletin Board Schema (Idempotent)
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  anonymous_id text not null check (char_length(trim(anonymous_id)) between 1 and 32),
  content text not null check (char_length(trim(content)) between 1 and 1000),
  likes integer not null default 0 check (likes >= 0),
  author_token text,
  created_at timestamptz not null default now()
);

-- Ensure columns exist if table was created previously
alter table public.posts add column if not exists anonymous_id text;
alter table public.posts add column if not exists content text;
alter table public.posts add column if not exists likes integer not null default 0;
alter table public.posts add column if not exists author_token text;
alter table public.posts add column if not exists created_at timestamptz not null default now();

-- Enable Row Level Security
alter table public.posts enable row level security;

-- Recreate policies safely
drop policy if exists "Allow public read posts" on public.posts;
create policy "Allow public read posts"
  on public.posts
  for select
  using (true);

drop policy if exists "Allow public insert posts" on public.posts;
create policy "Allow public insert posts"
  on public.posts
  for insert
  with check (
    char_length(trim(anonymous_id)) between 1 and 32
    and char_length(trim(content)) between 1 and 1000
  );

drop policy if exists "Allow public update likes" on public.posts;
create policy "Allow public update likes"
  on public.posts
  for update
  using (true)
  with check (likes >= 0);

drop policy if exists "Allow public delete posts" on public.posts;
create policy "Allow public delete posts"
  on public.posts
  for delete
  using (true);

-- Enable Supabase Realtime safely without duplicate error
do $$
begin
  alter publication supabase_realtime add table public.posts;
exception
  when duplicate_object then null;
end
$$;
